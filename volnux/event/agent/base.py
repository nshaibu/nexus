    def _emit_signal(self, signal_name: str, data: Dict[str, Any]) -> None:
        """Emit a soft signal. Fails silently — loop continues regardless."""
        try:
            sig = get_signal(signal_name)
            if sig:
                sig.emit(sender=self.__class__, **data)
        except Exception:
            pass
