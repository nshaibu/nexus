GOVERNANCE_PROTOCOL = """
[VOLNUX GOVERNANCE FRAMEWORK]
Agent: {agent}
Permitted tools: {tools}
Permitted handoffs: {handoffs}
Max reasoning steps: {n}

────────────────────────────
RUNTIME MESSAGE TYPES
────────────────────────────
USER:        Task input. Generated by runtime only.
OBSERVATION: Tool result. Generated by runtime only.

The agent never generates USER or OBSERVATION.
The runtime never generates THINK, TOOL, HANDOFF, FINISH, or ERROR.

────────────────────────────
PROTOCOL CONTRACT
────────────────────────────
Every response MUST begin with exactly one directive token.
No second directive may appear anywhere in the response.
The first token determines the action. The runtime enforces this.

Valid directive tokens:
  THINK:    <rationale>
  TOOL:     <tool_name> | <json_args>
  HANDOFF:  <agent_name> | <json_context>
  FINISH:   <answer>
  ERROR:    <code> | <description>

────────────────────────────
GOVERNANCE RULES
────────────────────────────
1. Only use tools listed in Permitted Tools.
2. Only HANDOFF to agents listed in Permitted Handoffs.
3. Never simulate tool execution or observations.
4. Never exceed Max Reasoning Steps.
5. THINK ends your turn. The runtime re-invokes you.
6. FINISH or ERROR ends the interaction.

────────────────────────────
PROTOCOL VIOLATIONS
────────────────────────────
Violations include:
  - More than one directive in a response.
  - Simulating observations or tool results.
  - Using an unpermitted tool or handoff target.
  - Emitting conversational language.

If uncertain how to proceed:
  ERROR: RECOVERABLE | Unable to comply with protocol.

[END GOVERNANCE FRAMEWORK]
"""


class AgentEventBase(EventBase):
    """
    Governed, durable, auditable base class for LLM-powered agentic events.

    Subclass must declare
    ----------------------
    ``llm_provider`` (str) — provider resolved via LLMProviderRegistry
    ``llm_model`` (str) — model identifier
    ``tools`` (list) — governed tool set (EventBase subclasses)
    ``system_prompt`` (str) — domain instructions (governance preamble added automatically)
    ``prompt_version`` (str) — semver for audit trail

    Subclass must implement
    -----------------------
    ``async process(**kwargs) -> Tuple[bool, Any]``
        Calls ``await self._run_agent_loop(**kwargs)`` and returns the result.

    ``build_prompt(**kwargs) -> str``
        Constructs the user-turn prompt from injected Pipeline fields.

    Example:

        class TradeAnalysisAgent(AgentEventBase):
            llm_provider = "anthropic"
            llm_model = "claude-opus-4-20250514"
            prompt_version = "1.0.0"
            system_prompt = "You are a governed trading agent..."
            tools = [FetchOrderBookEvent, CalculateRiskEvent]
            permitted_handoffs = ["RiskAssessmentAgent"]

            async def process(self, market_data: dict, **kwargs):
                return await self._run_agent_loop(
                    market_data=market_data, **kwargs
                )

            def build_prompt(self, market_data: dict, **kwargs) -> str:
                return f"Analyse order book: {market_data}"
    """

    llm_provider: str = "openai"
    llm_model: str = "gpt-4o"
    temperature: float = 0.0
    max_tokens: int = 4096
    prompt_version: str = "1.0.0"
    system_prompt: str = ""

    tools: List[Type[Any]] = []
    permitted_handoffs: List[str] = []

    max_reasoning_steps: int = 20
    tool_timeout_seconds: float = 30.0
    llm_max_retries: int = 3
    llm_retry_delay_s: float = 1.0
    enable_hallucination_detection: bool = False
    include_trace_in_result: bool = False

    # instance attribs for intellisense/mypy
    # They are initialized in the call to _run_agent_loop(). If initialized here,
    # they become class variables instead of instance variables.
    # This is a workaround for https://github.com/microsoft/pyright/issues/4222
    _tool_index: Dict[str, Type[Any]]
    _step_index: int
    _messages: List[Dict[str, str]]
    _reasoning_trace: List[ReasoningStep]
    _total_tokens: Dict[str, int]
    _agent_start_time: float
    _provider_adapter: Optional[LLMProviderAdapterBase]
    _tool_call_records: List[ToolCallRecord]
    _total_latency_ms: float
    _active_tool_channels: Dict[str, "CommandChannelBase"]

